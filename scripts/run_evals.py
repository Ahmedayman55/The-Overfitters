"""Run the guardrail trick-prompt evals and write evals/results.md.

    python scripts/run_evals.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import guardrails  # noqa: E402


def main() -> int:
    d = json.loads((ROOT / "evals" / "trick_prompts.json").read_text(encoding="utf-8"))
    rows, passed, total = [], 0, 0
    for c in d["requests_blocked"]:
        v = guardrails.screen_request(c["text"])
        ok = (not v.allowed) and v.category == c["expect"]
        rows.append(("refuse", c["text"], c["expect"], v.category or "allowed", ok))
    for t in d["requests_allowed"]:
        v = guardrails.screen_request(t)
        rows.append(("allow", t, "allowed", v.category or "allowed", v.allowed))
    for c in d["briefs_blocked"]:
        v = guardrails.screen_brief({"idea": c["idea"]})
        rows.append(("refuse brief", c["idea"], c["expect"], v.category or "allowed", (not v.allowed) and v.category == c["expect"]))
    for t in d["briefs_allowed"]:
        v = guardrails.screen_brief({"idea": t})
        rows.append(("allow brief", t, "allowed", v.category or "allowed", v.allowed))
    total = len(rows)
    passed = sum(r[4] for r in rows)
    md = [f"# Guardrail eval results: {passed}/{total} passed", "",
          "Generated by `scripts/run_evals.py` from `evals/trick_prompts.json` (rule layer only, no model needed).", "",
          "| Expected | Prompt | Expected category | Got | Pass |", "|---|---|---|---|---|"]
    md += [f"| {a} | {t.replace('|', '/')} | {e} | {g} | {'yes' if ok else 'NO'} |" for a, t, e, g, ok in rows]
    (ROOT / "evals" / "results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{passed}/{total} passed")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
